#!/usr/bin/env python
"""Generate `paper/sections/results.tex` from evaluation results."""

from __future__ import annotations

import sys as _sys
from pathlib import Path as _Path

_PROJECT_ROOT = _Path(__file__).resolve().parent.parent
if str(_PROJECT_ROOT) not in _sys.path:
    _sys.path.insert(0, str(_PROJECT_ROOT))

import json
from pathlib import Path

from src.evaluation.significance import compare_predictions
from src.utils.logger import get_logger

logger = get_logger(__name__)

LOGS_DIR = Path("experiments/logs")
RESULTS_TEX_PATH = Path("paper/sections/results.tex")
ABSTRACT_TEX_PATH = Path("paper/sections/abstract.tex")

METRIC_LABELS = {
    "closed_accuracy": "Closed-question accuracy",
    "open_bleu": "Open-question BLEU-4",
    "open_rouge_l": "Open-question ROUGE-L",
    "overall_exact_match": "Overall exact match",
}


def _read_jsonl(path: Path) -> list[dict]:
    with open(path, "r", encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def _read_json(path: Path) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _escape_latex(text: str) -> str:
    replacements = {"_": r"\_", "%": r"\%", "&": r"\&", "#": r"\#"}
    for char, escaped in replacements.items():
        text = text.replace(char, escaped)
    return text


def generate_results_tex() -> None:
    baseline_metrics_path = LOGS_DIR / "baseline_metrics.json"
    rag_metrics_path = LOGS_DIR / "rag_metrics.json"
    baseline_predictions_path = LOGS_DIR / "baseline_predictions.jsonl"
    rag_predictions_path = LOGS_DIR / "rag_predictions.jsonl"
    sweep_path = LOGS_DIR / "topk_sweep.json"

    required = [
        baseline_metrics_path,
        rag_metrics_path,
        baseline_predictions_path,
        rag_predictions_path,
    ]
    missing = [p for p in required if not p.is_file()]
    if missing:
        missing_str = ", ".join(str(p) for p in missing)
        raise FileNotFoundError(
            f"Missing required file(s): {missing_str}. "
            "Run scripts/run_baseline.py and scripts/run_rag_eval.py first."
        )

    baseline_metrics = _read_json(baseline_metrics_path)
    rag_metrics = _read_json(rag_metrics_path)
    baseline_records = _read_jsonl(baseline_predictions_path)
    rag_records = _read_jsonl(rag_predictions_path)
    significance_results = compare_predictions(baseline_records, rag_records)
    sweep_results = _read_json(sweep_path) if sweep_path.is_file() else None

    lines = _build_results_tex(baseline_metrics, rag_metrics, significance_results, sweep_results)
    RESULTS_TEX_PATH.write_text("\n".join(lines), encoding="utf-8")
    logger.info("Wrote %s", RESULTS_TEX_PATH)

    _write_abstract_number_reference(baseline_metrics, rag_metrics, significance_results)


def _build_results_tex(
    baseline_metrics: dict,
    rag_metrics: dict,
    significance_results: dict,
    sweep_results: dict | None,
) -> list[str]:
    lines = [
        "% AUTO-GENERATED by scripts/generate_paper_results.py.",
        "% Do NOT hand-edit -- re-run the script after any new evaluation run.",
        f"% Source: {LOGS_DIR}/baseline_metrics.json, rag_metrics.json,",
        f"%         baseline_predictions.jsonl, rag_predictions.jsonl"
        + (", topk_sweep.json" if sweep_results else ""),
        "",
        "Table~\\ref{tab:headline-results} reports headline metrics for both",
        "conditions on the VQA-RAD test split, computed by the identical",
        "scoring code (\\texttt{src/evaluation/metrics.py}) for both.",
        "",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Baseline vs.\\ retrieval-augmented results on the VQA-RAD test split.}",
        "\\label{tab:headline-results}",
        "\\begin{tabular}{@{}lccc@{}}",
        "\\toprule",
        "Metric & Baseline & RAG & Delta \\\\",
        "\\midrule",
    ]
    for key, label in METRIC_LABELS.items():
        b = baseline_metrics.get(key)
        r = rag_metrics.get(key)
        if b is None or r is None:
            continue
        lines.append(f"{label} & {b:.4f} & {r:.4f} & {r - b:+.4f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]

    if significance_results:
        lines += [
            "Table~\\ref{tab:significance} reports the paired bootstrap",
            "significance test (10{,}000 resamples, 95\\% confidence interval)",
            "for each comparison, computed by",
            "\\texttt{src/evaluation/significance.py}.",
            "",
            "\\begin{table}[t]",
            "\\centering",
            "\\caption{Paired bootstrap significance test results.}",
            "\\label{tab:significance}",
            "\\begin{tabular}{@{}lcccc@{}}",
            "\\toprule",
            "Comparison & Delta & 95\\% CI & $p$ & Sig.\\ ($p<0.05$) \\\\",
            "\\midrule",
        ]
        for name, result in significance_results.items():
            ci = f"[{result['ci_lower']:.4f}, {result['ci_upper']:.4f}]"
            sig = "Yes" if result["significant_at_0_05"] else "No"
            escaped_name = _escape_latex(name)
            lines.append(
                f"{escaped_name} & {result['observed_delta']:+.4f} & {ci} & "
                f"{result['p_value']:.4f} & {sig} \\\\"
            )
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]

    if sweep_results:
        lines += [
            "Table~\\ref{tab:topk-sweep} reports the top-$k$ sweep from",
            "\\texttt{scripts/run\\_experiments.py}.",
            "",
            "\\begin{table}[t]",
            "\\centering",
            "\\caption{Retrieval-augmented accuracy as a function of top-$k$.}",
            "\\label{tab:topk-sweep}",
            "\\begin{tabular}{@{}lccc@{}}",
            "\\toprule",
            "$k$ & Closed Acc.\\ & Open BLEU & Open ROUGE-L \\\\",
            "\\midrule",
        ]
        for k in sorted(sweep_results, key=lambda x: int(x)):
            m = sweep_results[k]
            lines.append(
                f"{k} & {m['closed_accuracy']:.4f} & {m['open_bleu']:.4f} & "
                f"{m['open_rouge_l']:.4f} \\\\"
            )
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]

    lines += [
        "TODO(author): one to two paragraphs of prose walking through these",
        "tables -- which metrics moved, by how much, and whether the",
        "significance test supports treating the delta as reliable. Do not",
        "restate every number in the tables verbatim; interpret them.",
    ]
    return lines


def _write_abstract_number_reference(
    baseline_metrics: dict,
    rag_metrics: dict,
    significance_results: dict,
) -> None:
    """Prepend a comment block of headline numbers to abstract.tex.

    Does not write abstract prose automatically -- a good abstract requires
    human judgment about what to emphasize, which this script has no basis
    for. This only removes the tedium of hunting through JSON files to find
    the numbers a human author needs while writing that prose by hand.
    """
    if not ABSTRACT_TEX_PATH.is_file():
        return

    existing_text = ABSTRACT_TEX_PATH.read_text(encoding="utf-8")
    if "AUTO-INSERTED HEADLINE NUMBERS" in existing_text:
        marker = "% ===== END AUTO-INSERTED HEADLINE NUMBERS ====="
        if marker in existing_text:
            existing_text = existing_text.split(marker, 1)[1].lstrip("\n")

    number_lines = ["% ===== AUTO-INSERTED HEADLINE NUMBERS (for the author to write from) ====="]
    for key, label in METRIC_LABELS.items():
        b = baseline_metrics.get(key)
        r = rag_metrics.get(key)
        if b is None or r is None:
            continue
        number_lines.append(f"% {label}: baseline={b:.4f}, rag={r:.4f}, delta={r - b:+.4f}")
    for name, result in significance_results.items():
        number_lines.append(
            f"% {name}: p={result['p_value']:.4f}, "
            f"significant={result['significant_at_0_05']}"
        )
    number_lines.append("% ===== END AUTO-INSERTED HEADLINE NUMBERS =====")
    number_lines.append("")

    ABSTRACT_TEX_PATH.write_text(
        "\n".join(number_lines) + existing_text, encoding="utf-8"
    )
    logger.info("Updated %s with headline numbers for reference", ABSTRACT_TEX_PATH)


if __name__ == "__main__":
    generate_results_tex()
